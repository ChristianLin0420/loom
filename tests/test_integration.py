def test_real_proposal_log_prob_is_negative_and_finite():
    p = _proposal()
    z, lang = torch.randn(3, C.K, C.D), torch.randn(3, 16, 1152)
    lp = p.log_prob(z, lang, p.sample(z, lang, n=1)[:, 0])
    assert lp.shape == (3,)
    assert torch.isfinite(lp).all() and (lp <= 0).all()


def test_real_proposal_argmax_is_deterministic():
    """R0 inference is `c <- argmax pi_c`, with no search. It must not wobble."""
    p = _proposal()
    z, lang = torch.randn(2, C.K, C.D), torch.randn(2, 16, 1152)
    fn = getattr(p, "argmax", None)
    if fn is None:
        pytest.skip("proposal has no argmax()")
    a, b = fn(z, lang), fn(z, lang)
    assert torch.allclose(a, b)
    C.assert_simplex(a)


