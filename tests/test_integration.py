def _sources() -> list[Path]:
    pkg = ROOT / "loom"
    return [p for p in pkg.rglob("*.py")] if pkg.exists() else []


def test_no_view_as_complex_anywhere():
    """PLAN §9: there is no complex-bf16 dtype and the whole run is bf16."""
    bad = [p for p in _sources() if "view_as_complex" in p.read_text()]
    assert not bad, f"view_as_complex found in {[str(p.relative_to(ROOT)) for p in bad]}"


def test_no_compose_on_the_bank():
    """PLAN §9: multiplying lambdas alone silently discards the bias."""
    bank_py = ROOT / "loom" / "model" / "bank.py"
    if not bank_py.exists():
        pytest.skip("bank.py not landed")
    src = bank_py.read_text()
    assert "def compose" not in src, "bank must not expose compose(); rollout is sequential"


def test_eval_does_not_import_model_internals():
    """PLAN §4.F: eval depends on nothing but contracts.Policy."""
    ev = ROOT / "loom" / "eval"
    if not ev.exists():
        pytest.skip("eval not landed")
    offenders = []
    for p in ev.rglob("*.py"):
        for line in p.read_text().splitlines():
            s = line.strip()
            if not (s.startswith("import ") or s.startswith("from ")):
                continue          # lazy imports inside functions are allowed
            if "loom.model" in s or "loom.heads" in s or "loom.train" in s:
                offenders.append(f"{p.relative_to(ROOT)}: {s}")
    assert not offenders, "eval must couple only to contracts.Policy:\n" + "\n".join(offenders)


def test_sbatch_files_name_only_real_partitions():
    """batch_block1/2/3 do not exist on this cluster; naming one is a 0-second
    job failure that looks like a code bug."""
    files = list((ROOT / "loom" / "train" / "slurm").glob("*.sbatch")) if \
        (ROOT / "loom" / "train" / "slurm").exists() else []
    files += list((ROOT / "scripts").glob("*.sbatch")) if (ROOT / "scripts").exists() else []
    if not files:
        pytest.skip("no sbatch files landed")
    for f in files:
        src = f.read_text()
        for ghost in ("batch_block1", "batch_block2", "batch_block3"):
            assert ghost not in src, f"{f.name} names nonexistent partition {ghost}"
