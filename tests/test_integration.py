def test_proposal_into_real_bank_rollout():
    """The R3 search path end to end: pi_c samples, the real bank rolls out,
    and the leaf is still a valid bounded belief."""
    p, bank = _proposal(), _bank()
    z = torch.randn(2, C.K, C.D)
    lang = torch.randn(2, 16, 1152)

    seq = getattr(p, "sample_seq", None)
    if seq is None:
        pytest.skip("proposal has no sample_seq()")
    c_seq = seq(z, lang, n=8, depth=C.DEPTH)
    assert c_seq.shape == (2, 8, C.DEPTH, C.M)

    leaf = bank.rollout(c_seq, z)
    assert leaf.shape == (2, 8, C.K, C.D)
    C.assert_belief(leaf)


def test_q_delta_coefficients_drive_the_real_bank():
    """q_Delta's output must be directly usable by the bank — that is the whole
    point of putting both encoders on one simplex."""
    q = _instantiate(_try("loom.heads.q_delta", "QDelta", "QDeltaHead"))
    bank = _bank()
    z, zn = torch.randn(4, C.K, C.D), torch.randn(4, C.K, C.D)
    c = q(z, zn)
    C.assert_simplex(c)
    C.assert_belief(bank.step(c, z))


def test_decoder_segment_feeds_q_action_round_trip():
    """The realizability gate in search needs q_a(D_e(z,c), z) to typecheck."""
    dec = _instantiate(_try("loom.heads.decoder", "Decoder", "FlowDecoder"),
                       embodiments=("libero_franka",))
