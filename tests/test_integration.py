def _try(module: str, *names: str):
    """Import the first of `names` that exists in `module`, else skip.

    Teams pick their own class names; the contract is the Protocol, not the
    spelling. Trying several keeps the gate from failing on a naming choice.
    """
    try:
        mod = importlib.import_module(module)
    except Exception as exc:                                 # not landed yet
        pytest.skip(f"{module} not importable: {type(exc).__name__}: {exc}")
    for n in names:
        obj = getattr(mod, n, None)
        if obj is not None:
            return obj
    # Fall back to any class in the module satisfying nothing in particular.
    pytest.skip(f"{module} has none of {names}")


def _instantiate(cls, **kw):
    """Construct with only the kwargs the signature actually accepts."""
    try:
        sig = inspect.signature(cls)
        ok = {k: v for k, v in kw.items() if k in sig.parameters}
        return cls(**ok)
    except Exception as exc:
        pytest.skip(f"cannot instantiate {cls.__name__}: {type(exc).__name__}: {exc}")


