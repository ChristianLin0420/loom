#: PLAN §4.B asks for 10k draws. mix() expands each draw to (K, D//2) twice, so
#: 10k at once is ~2 GiB per tensor and gets OOM-killed. Same coverage, chunked.
_DRAWS, _CHUNK = 10_000, 500


def test_real_bank_is_contractive():
    """The single most load-bearing invariant in the method."""
    bank = _bank()
    for _ in range(_DRAWS // _CHUNK):
        C.assert_contractive(bank, n=_CHUNK)


def test_real_bank_bias_is_bounded():
    bank = _bank()
    for _ in range(_DRAWS // _CHUNK):
        C.assert_bias_bounded(bank, n=_CHUNK)


def test_real_bank_step_shape_and_broadcast():
    bank = _bank()
    z = torch.randn(3, C.K, C.D)
    out = bank.step(S.sparse_simplex(3), z)
    assert out.shape == z.shape
    C.assert_belief(out)

    zc = torch.randn(3, 5, C.K, C.D)
    outc = bank.step(S.sparse_simplex(3, 5), zc)
    assert outc.shape == zc.shape


def test_real_rollout_matches_sequential_step():
    """Catches the affine-composition bug: composing (A2,b2) after (A1,b1) is
    (A2A1, A2b1+b2), so multiplying lambdas alone silently drops the bias."""
    bank = _bank()
    z0 = torch.randn(2, C.K, C.D)
    c = S.sparse_simplex(2, 1, C.DEPTH)

    manual = z0.unsqueeze(1)
    for d in range(C.DEPTH):
        manual = bank.step(c[:, :, d], manual)

    assert torch.allclose(bank.rollout(c, z0), manual, atol=1e-5)


def test_real_rollout_does_not_explode():
    bank = _bank()
    z0 = torch.randn(8, C.K, C.D)
    leaves = bank.rollout(S.sparse_simplex(8, 1, C.DEPTH), z0)
    bound = (C.RHO ** C.DEPTH) * z0.flatten(1).norm(dim=1) \
        + (1 - C.RHO ** C.DEPTH) / (1 - C.RHO) * C.B_MAX
    assert (leaves.squeeze(1).flatten(1).norm(dim=1) <= bound + 1e-3).all()


def test_real_bank_stays_bf16():
    bank = _bank().to(torch.bfloat16)
    z = torch.randn(2, C.K, C.D, dtype=torch.bfloat16)
    out = bank.step(S.sparse_simplex(2, dtype=torch.bfloat16), z)
    assert out.dtype == torch.bfloat16 and not out.is_complex()


