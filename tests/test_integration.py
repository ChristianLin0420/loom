def test_real_estimator_shape_and_recurrence():
    cls = _try("loom.model.estimator", "Estimator", "BeliefEstimator", "PerceiverEstimator")
    est = _instantiate(cls, feat_dim=1152, embodiments=("libero_franka",))
    assert isinstance(est, C.Estimator)

    feats = S.make_obs_feats(b=2)
    z1 = est(feats, None)
